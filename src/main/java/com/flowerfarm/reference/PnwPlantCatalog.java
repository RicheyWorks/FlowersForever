    private PnwPlantCatalog() {
    }

    public static List<PnwPlantProfile> all() {
        return new java.util.ArrayList<>(PLANTS);
    }

    public static List<String> types() {
        return PLANTS.stream().map(PnwPlantProfile::type).distinct().sorted().toList();
    }

    public static List<Source> sources() {
        return java.util.stream.Stream.concat(
                        PLANTS.stream().map(PnwPlantProfile::source),
                        SUPPLEMENTAL_SOURCES.stream())
                .distinct()
                .sorted(Comparator.comparing(Source::organization).thenComparing(Source::title))
                .toList();
    }

    private static PnwPlantProfile p(String commonName, String scientificName, String type,
                                     boolean nativePlant, String light, String moisture,
                                     String season, String uses, String fieldNotes, Source source) {
        return new PnwPlantProfile(commonName, scientificName, type, nativePlant, light,
                moisture, season, uses, fieldNotes, source);
    }

    private static Source source(String organization, String title, String url) {
        return new Source(organization, title, url);
    }
