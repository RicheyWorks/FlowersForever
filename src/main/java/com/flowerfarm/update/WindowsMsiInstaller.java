package com.flowerfarm.update;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;
import java.util.Optional;

/**
 * Windows hand-off. A {@code .cmd} script waits (up to two minutes) for this
 * process to exit, runs {@code msiexec /i <msi> /passive /norestart} with a
 * verbose log, records the exit code, and starts the installed launcher again.
 * The same MSI upgrade code and {@code AllowDowngrades=yes} (jpackage defaults)
 * let the same command install a newer version or roll back to the previous one.
 * Java starts console programs from a windowless app with CREATE_NO_WINDOW, so
 * no console window appears; only the Windows Installer progress bar and, for a
 * per-machine install, the Windows permission prompt are shown.
 */
public final class WindowsMsiInstaller implements PlatformInstaller {

    private final Optional<Path> launcher;
    private final ProcessStarter starter;
    private final long processId;
    private final Path systemRoot;

    public WindowsMsiInstaller(Optional<Path> launcher, ProcessStarter starter, long processId, Path systemRoot) {
        this.launcher = launcher;
        this.starter = starter;
        this.processId = processId;
        this.systemRoot = systemRoot;
    }

    public static WindowsMsiInstaller forThisProcess(Optional<Path> launcher) {
        String root = System.getenv("SystemRoot");
        return new WindowsMsiInstaller(launcher, ProcessStarter.system(), ProcessHandle.current().pid(),
                Path.of(root == null || root.isBlank() ? "C:\\Windows" : root));
    }

    @Override
    public boolean canInstall() {
        return launcher.map(path -> path.getFileName() != null
                && path.getFileName().toString().toLowerCase(Locale.ROOT).endsWith(".exe")).orElse(false);
    }

    @Override
    public Path launch(VerifiedPackage installer, Path workDirectory, Purpose purpose) throws IOException {
        if (!canInstall()) {
            throw new IOException(UpdateMessages.CANNOT_INSTALL_HERE);
        }
        Files.createDirectories(workDirectory);
        String tag = purpose.name().toLowerCase(Locale.ROOT) + "-" + installer.version();
        Path script = workDirectory.resolve("apply-" + tag + ".cmd");
        Path log = workDirectory.resolve("msiexec-" + tag + ".log");
        Path result = workDirectory.resolve("msiexec-" + tag + ".exitcode");
        String content = script(installer.file(), log, result);
        Files.writeString(script, content, StandardCharsets.UTF_8);
        Path cmd = systemRoot.resolve("System32").resolve("cmd.exe");
        starter.start(List.of(cmd.toString(), "/d", "/c", PlatformInstaller.scriptSafe(script)), workDirectory);
        return script;
    }

    String script(Path msi, Path log, Path result) throws IOException {
        String msiexec = PlatformInstaller.scriptSafe(systemRoot.resolve("System32").resolve("msiexec.exe"));
        String app = PlatformInstaller.scriptSafe(launcher.orElseThrow());
        return String.join("\r\n",
                "@echo off",
                "rem FlowersForever update hand-off. Generated by the app; safe to delete afterwards.",
                "setlocal",
                "set /a FF_WAIT=0",
                ":wait",
                "tasklist /FI \"PID eq " + processId + "\" /NH 2>nul | find \" " + processId + " \" >nul",
                "if errorlevel 1 goto install",
                "set /a FF_WAIT+=1",
                "if %FF_WAIT% GEQ 120 goto install",
                "ping -n 2 127.0.0.1 >nul",
                "goto wait",
                ":install",
                "\"" + msiexec + "\" /i \"" + PlatformInstaller.scriptSafe(msi) + "\" /passive /norestart /l*v \""
                        + PlatformInstaller.scriptSafe(log) + "\"",
                "> \"" + PlatformInstaller.scriptSafe(result) + "\" echo %ERRORLEVEL%",
                "start \"\" \"" + app + "\"",
                "endlocal",
                "");
    }
}
