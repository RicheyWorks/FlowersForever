package com.flowerfarm.update;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;
import java.util.Optional;

/**
 * macOS hand-off. A shell script waits for this process to exit, mounts the
 * DMG read-only, swaps the .app bundle (keeping the old bundle until the copy
 * succeeds), detaches, and reopens the app. Not yet exercised on a real Mac.
 */
public final class MacDmgInstaller implements PlatformInstaller {

    private final Optional<Path> appBundle;
    private final ProcessStarter starter;
    private final long processId;

    public MacDmgInstaller(Optional<Path> launcher, ProcessStarter starter, long processId) {
        this.appBundle = launcher.flatMap(MacDmgInstaller::bundleOf);
        this.starter = starter;
        this.processId = processId;
    }

    static Optional<Path> bundleOf(Path launcher) {
        for (Path current = launcher.toAbsolutePath(); current != null; current = current.getParent()) {
            Path name = current.getFileName();
            if (name != null && name.toString().toLowerCase(Locale.ROOT).endsWith(".app")) {
                return Optional.of(current);
            }
        }
        return Optional.empty();
    }

    @Override
    public boolean canInstall() {
        return appBundle.isPresent();
    }

    @Override
    public Path launch(VerifiedPackage installer, Path workDirectory, Purpose purpose) throws IOException {
        if (!canInstall()) {
            throw new IOException(UpdateMessages.CANNOT_INSTALL_HERE);
        }
        Files.createDirectories(workDirectory);
        String tag = purpose.name().toLowerCase(Locale.ROOT) + "-" + installer.version();
        Path script = workDirectory.resolve("apply-" + tag + ".sh");
        Path log = workDirectory.resolve("install-" + tag + ".log");
        Files.writeString(script, script(installer.file(), log), StandardCharsets.UTF_8);
        starter.start(List.of("/bin/sh", PlatformInstaller.scriptSafe(script)), workDirectory);
        return script;
    }

    String script(Path dmg, Path log) throws IOException {
        String app = PlatformInstaller.scriptSafe(appBundle.orElseThrow());
        return String.join("\n",
                "#!/bin/sh",
                "# FlowersForever update hand-off. Generated by the app; safe to delete afterwards.",
                "exec >>\"" + PlatformInstaller.scriptSafe(log) + "\" 2>&1",
                "i=0",
                "while kill -0 " + processId + " 2>/dev/null && [ $i -lt 120 ]; do sleep 1; i=$((i+1)); done",
                "APP=\"" + app + "\"",
                "MNT=$(mktemp -d /tmp/flowersforever-update.XXXXXX) || exit 1",
                "if hdiutil attach -nobrowse -readonly -mountpoint \"$MNT\" \""
                        + PlatformInstaller.scriptSafe(dmg) + "\"; then",
                "  NEW=$(find \"$MNT\" -maxdepth 1 -name '*.app' -type d | head -n 1)",
                "  if [ -n \"$NEW\" ]; then",
                "    rm -rf \"$APP.ff-previous\"",
                "    if mv \"$APP\" \"$APP.ff-previous\" && ditto \"$NEW\" \"$APP\"; then",
                "      rm -rf \"$APP.ff-previous\"; echo installed",
                "    else",
                "      rm -rf \"$APP\"; mv \"$APP.ff-previous\" \"$APP\"; echo install-failed",
                "    fi",
                "  fi",
                "  hdiutil detach \"$MNT\" -quiet",
                "fi",
                "rmdir \"$MNT\" 2>/dev/null",
                "open \"$APP\"",
                "");
    }
}
