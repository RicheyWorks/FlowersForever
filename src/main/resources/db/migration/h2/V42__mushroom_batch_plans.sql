-- Plans do not record actual inoculation, harvest, stock, or sales events.
CREATE TABLE mushroom_batch_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_name VARCHAR(120) NOT NULL,
    mushroom_species VARCHAR(120) NOT NULL,
    growing_method VARCHAR(120) NOT NULL,
    substrate VARCHAR(120) NOT NULL,
    growing_site VARCHAR(120) NOT NULL,
    planned_inoculation_date DATE,
    planned_fruiting_start DATE,
    planned_fruiting_end DATE,
    intended_channel VARCHAR(120) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_mushroom_batch_name CHECK (TRIM(batch_name) <> ''),
    CONSTRAINT ck_mushroom_species CHECK (TRIM(mushroom_species) <> ''),
    CONSTRAINT ck_mushroom_fruiting_start CHECK (
        planned_fruiting_start IS NULL OR planned_inoculation_date IS NULL
        OR planned_fruiting_start >= planned_inoculation_date),
    CONSTRAINT ck_mushroom_fruiting_end CHECK (
        planned_fruiting_end IS NULL OR
        (planned_fruiting_start IS NOT NULL
         AND planned_fruiting_end >= planned_fruiting_start)),
    CONSTRAINT ck_mushroom_stage CHECK (
        stage IN ('PLANNED', 'INOCULATION_WINDOW', 'INCUBATING', 'FRUITING_WINDOW'))
);

CREATE INDEX idx_mushroom_batch_species
    ON mushroom_batch_plans(mushroom_species);
CREATE INDEX idx_mushroom_batch_fruiting_start
    ON mushroom_batch_plans(planned_fruiting_start);
