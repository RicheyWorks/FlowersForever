-- Local cultivation planning only; no compliance identifiers or sales linkage.
CREATE TABLE cannabis_cultivation_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_name VARCHAR(120) NOT NULL,
    cultivar VARCHAR(120) NOT NULL,
    area VARCHAR(128) NOT NULL,
    plant_count INTEGER NOT NULL,
    start_date DATE NOT NULL,
    planned_harvest_date DATE NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_cannabis_batch_plants CHECK (plant_count BETWEEN 0 AND 1000000),
    CONSTRAINT ck_cannabis_batch_dates CHECK (planned_harvest_date >= start_date),
    CONSTRAINT ck_cannabis_batch_stage CHECK (stage IN (
        'PLANNED', 'PROPAGATING', 'VEGETATIVE', 'FLOWERING',
        'HARVESTED', 'COMPLETE', 'CANCELLED'))
);

CREATE INDEX idx_cannabis_batch_start ON cannabis_cultivation_batches(start_date);
CREATE INDEX idx_cannabis_batch_stage ON cannabis_cultivation_batches(stage);
