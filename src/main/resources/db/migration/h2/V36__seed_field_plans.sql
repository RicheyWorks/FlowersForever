-- Plans do not record seed cleaning, testing, certification, stock, or sales.
CREATE TABLE seed_field_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_name VARCHAR(120) NOT NULL,
    seed_crop VARCHAR(120) NOT NULL,
    variety VARCHAR(120) NOT NULL,
    acres DECIMAL(9, 2),
    previous_crop VARCHAR(120) NOT NULL,
    planned_sowing_date DATE,
    planned_flowering_start DATE,
    planned_flowering_end DATE,
    planned_harvest_start DATE NOT NULL,
    planned_harvest_end DATE,
    intended_use VARCHAR(120) NOT NULL,
    isolation_notes VARCHAR(1000) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_seed_field_name CHECK (TRIM(field_name) <> ''),
    CONSTRAINT ck_seed_field_crop CHECK (TRIM(seed_crop) <> ''),
    CONSTRAINT ck_seed_field_acres CHECK (acres IS NULL OR (acres > 0 AND acres <= 1000000.00)),
    CONSTRAINT ck_seed_field_sowing CHECK (
        planned_sowing_date IS NULL OR planned_sowing_date <= planned_harvest_start),
    CONSTRAINT ck_seed_field_flowering_start CHECK (
        planned_flowering_start IS NULL OR planned_flowering_start <= planned_harvest_start),
    CONSTRAINT ck_seed_field_flowering_end CHECK (
        planned_flowering_end IS NULL OR planned_flowering_end <= planned_harvest_start),
    CONSTRAINT ck_seed_field_flowering_order CHECK (
        planned_flowering_start IS NULL OR planned_flowering_end IS NULL
        OR planned_flowering_end >= planned_flowering_start),
    CONSTRAINT ck_seed_field_sowing_flowering_start CHECK (
        planned_sowing_date IS NULL OR planned_flowering_start IS NULL
        OR planned_flowering_start >= planned_sowing_date),
    CONSTRAINT ck_seed_field_sowing_flowering_end CHECK (
        planned_sowing_date IS NULL OR planned_flowering_end IS NULL
        OR planned_flowering_end >= planned_sowing_date),
    CONSTRAINT ck_seed_field_harvest_dates CHECK (
        planned_harvest_end IS NULL OR planned_harvest_end >= planned_harvest_start),
    CONSTRAINT ck_seed_field_stage CHECK (
        stage IN ('PLANNED', 'SOWN', 'ESTABLISHED', 'FLOWERING', 'HARVEST_WINDOW'))
);

CREATE INDEX idx_seed_field_crop ON seed_field_plans(seed_crop);
CREATE INDEX idx_seed_field_harvest_start ON seed_field_plans(planned_harvest_start);
