-- FlowersForever 1.0 schema. Existing non-empty databases are baselined at V1;
-- new databases execute this migration before Hibernate validates the mapping.

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_type VARCHAR(32) NOT NULL,
    phone VARCHAR(64),
    notes VARCHAR(2000),
    contact_name VARCHAR(255),
    email VARCHAR(255),
    name VARCHAR(255) NOT NULL
);

CREATE TABLE customer_orders (
    order_date DATE NOT NULL,
    customer_id BIGINT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(32) NOT NULL,
    notes VARCHAR(2000),
    CONSTRAINT fk_customer_orders_customer
        FOREIGN KEY (customer_id) REFERENCES customers(id)
);

CREATE TABLE order_lines (
    quantity FLOAT(53) NOT NULL,
    unit_price FLOAT(53) NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    unit VARCHAR(64) NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    CONSTRAINT fk_order_lines_order
        FOREIGN KEY (order_id) REFERENCES customer_orders(id)
);

CREATE TABLE harvest_log (
    harvest_date DATE NOT NULL,
    quantity FLOAT(53) NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit VARCHAR(64) NOT NULL,
    bed_or_field VARCHAR(128),
    notes VARCHAR(2000),
    crop_name VARCHAR(255) NOT NULL
);

CREATE TABLE inventory_items (
    cost FLOAT(53) NOT NULL,
    price FLOAT(53) NOT NULL,
    quantity INTEGER NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit VARCHAR(64) NOT NULL,
    category VARCHAR(128) NOT NULL,
    notes VARCHAR(2000),
    name VARCHAR(255) NOT NULL
);

CREATE TABLE sync_history (
    record_count INTEGER,
    success BOOLEAN NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    operation VARCHAR(16) NOT NULL,
    connector_name VARCHAR(64) NOT NULL,
    message VARCHAR(512) NOT NULL,
    detail VARCHAR(2000)
);

CREATE INDEX idx_harvest_date ON harvest_log(harvest_date);
CREATE INDEX idx_sync_history_occurred ON sync_history(occurred_at);
