-- Durable mobile photo evidence with content-addressed files under the farm data folder.

CREATE TABLE field_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_record_id BIGINT NOT NULL,
    byte_size BIGINT NOT NULL,
    captured_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    target_type VARCHAR(32) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    media_type VARCHAR(64) NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    storage_key VARCHAR(80) NOT NULL,
    caption VARCHAR(500),
    CONSTRAINT ck_field_attachment_target_id CHECK (target_record_id > 0),
    CONSTRAINT ck_field_attachment_size CHECK (byte_size BETWEEN 1 AND 15728640),
    CONSTRAINT ck_field_attachment_target_type CHECK (
        target_type = 'PRODUCTION_TASK'),
    CONSTRAINT ck_field_attachment_sha256 CHECK (LENGTH(sha256) = 64)
);

CREATE INDEX idx_field_attachment_target
    ON field_attachments(target_type, target_record_id, captured_at);
CREATE INDEX idx_field_attachment_created ON field_attachments(created_at);

ALTER TABLE worker_action_receipts DROP CONSTRAINT ck_worker_action_type;

ALTER TABLE worker_action_receipts ADD CONSTRAINT ck_worker_action_type CHECK (
    action IN ('LOG_HARVEST', 'COMPLETE_TASK', 'COUNT_INVENTORY',
               'COMPLETE_ORDER', 'ADD_ATTACHMENT')
);
