-- Dated checks may repeat for a hive. These are observations, not diagnoses,
-- registration, treatment advice, honey inventory, or sales records.
CREATE TABLE hive_checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apiary_name VARCHAR(120) NOT NULL,
    hive_label VARCHAR(120) NOT NULL,
    check_date DATE NOT NULL,
    purpose VARCHAR(120) NOT NULL,
    status VARCHAR(24) NOT NULL,
    next_check_date DATE,
    observations VARCHAR(2000) NOT NULL,
    actions VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_hive_check_apiary CHECK (TRIM(apiary_name) <> ''),
    CONSTRAINT ck_hive_check_hive CHECK (TRIM(hive_label) <> ''),
    CONSTRAINT ck_hive_check_next_date CHECK (
        next_check_date IS NULL OR next_check_date >= check_date),
    CONSTRAINT ck_hive_check_status CHECK (
        status IN ('NOT_ASSESSED', 'ACTIVE', 'NEEDS_FOLLOW_UP',
                   'OVERWINTERING', 'INACTIVE'))
);

CREATE INDEX idx_hive_checks_apiary_date
    ON hive_checks(apiary_name, check_date);
