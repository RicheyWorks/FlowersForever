-- Visual crop and bed plans from sowing through expected harvest.

CREATE TABLE season_plan_entries (
    season_year INTEGER NOT NULL,
    expected_stems INTEGER NOT NULL,
    bed_feet FLOAT(53) NOT NULL,
    sow_date DATE NOT NULL,
    transplant_date DATE,
    harvest_start DATE NOT NULL,
    harvest_end DATE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(24) NOT NULL,
    crop_name VARCHAR(120) NOT NULL,
    variety VARCHAR(120),
    bed_or_field VARCHAR(128) NOT NULL,
    notes VARCHAR(1000),
    CONSTRAINT chk_season_plan_year CHECK (season_year BETWEEN 2000 AND 2200),
    CONSTRAINT chk_season_plan_bed_feet CHECK (bed_feet > 0),
    CONSTRAINT chk_season_plan_stems CHECK (expected_stems >= 0),
    CONSTRAINT chk_season_plan_dates CHECK (
        (transplant_date IS NULL OR transplant_date >= sow_date)
        AND harvest_start >= COALESCE(transplant_date, sow_date)
        AND harvest_end >= harvest_start)
);

CREATE INDEX idx_season_plan_year ON season_plan_entries(season_year);
CREATE INDEX idx_season_plan_bed ON season_plan_entries(bed_or_field);
CREATE INDEX idx_season_plan_harvest ON season_plan_entries(harvest_start, harvest_end);
