-- A planning snapshot only. It is not an animal identity, movement, health,
-- production, sales, or regulatory tracking ledger.
CREATE TABLE herd_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name VARCHAR(120) NOT NULL,
    species VARCHAR(120) NOT NULL,
    head_count INTEGER NOT NULL,
    location VARCHAR(128) NOT NULL,
    purpose VARCHAR(120) NOT NULL,
    next_check_date DATE,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_herd_group_name CHECK (TRIM(group_name) <> ''),
    CONSTRAINT ck_herd_group_species CHECK (TRIM(species) <> ''),
    CONSTRAINT ck_herd_group_head_count CHECK (head_count BETWEEN 0 AND 1000000)
);

CREATE INDEX idx_herd_group_species ON herd_groups(species);
CREATE INDEX idx_herd_group_next_check ON herd_groups(next_check_date);
