CREATE TABLE farm_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id VARCHAR(80) NOT NULL,
    reading_key VARCHAR(160) NOT NULL,
    device_id VARCHAR(120) NOT NULL,
    metric VARCHAR(80) NOT NULL,
    unit VARCHAR(40) NOT NULL,
    measured_value DECIMAL(30, 12),
    quality VARCHAR(12) NOT NULL,
    observed_at VARCHAR(40) NOT NULL,
    received_at VARCHAR(40) NOT NULL,
    location VARCHAR(180) NOT NULL,
    raw_frame CLOB NOT NULL,
    CONSTRAINT uq_farm_reading_source_key UNIQUE (source_id, reading_key)
);
CREATE INDEX idx_farm_readings_source_cursor ON farm_readings (source_id, id);
