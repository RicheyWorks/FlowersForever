-- Plans do not create harvest, inventory, order, or winery production records.
CREATE TABLE vineyard_block_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_name VARCHAR(120) NOT NULL,
    location VARCHAR(120) NOT NULL,
    grape_variety VARCHAR(120) NOT NULL,
    acres DECIMAL(9, 2),
    planned_harvest_start DATE,
    planned_harvest_end DATE,
    destination VARCHAR(24) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_vineyard_block_name CHECK (TRIM(block_name) <> ''),
    CONSTRAINT ck_vineyard_grape_variety CHECK (TRIM(grape_variety) <> ''),
    CONSTRAINT ck_vineyard_acres CHECK (acres IS NULL OR (acres > 0 AND acres <= 1000000.00)),
    CONSTRAINT ck_vineyard_harvest_window CHECK (
        planned_harvest_start IS NULL OR planned_harvest_end IS NULL
        OR planned_harvest_end >= planned_harvest_start),
    CONSTRAINT ck_vineyard_destination CHECK (
        destination IN ('UNDECIDED', 'WINERY_BUYER', 'ESTATE_WINERY',
                        'FRESH_MARKET', 'OTHER')),
    CONSTRAINT ck_vineyard_stage CHECK (
        stage IN ('PLANNED', 'GROWING', 'HARVEST_WINDOW', 'POST_HARVEST'))
);

CREATE INDEX idx_vineyard_block_variety ON vineyard_block_plans(grape_variety);
CREATE INDEX idx_vineyard_block_harvest_start ON vineyard_block_plans(planned_harvest_start);
