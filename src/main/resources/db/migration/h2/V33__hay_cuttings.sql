-- Cutting plans do not post bale quantities, feed, inventory, or orders.
CREATE TABLE hay_cuttings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_name VARCHAR(120) NOT NULL,
    forage_crop VARCHAR(120) NOT NULL,
    cutting_number INTEGER NOT NULL,
    acres DECIMAL(9, 2),
    planned_cut_date DATE NOT NULL,
    planned_bale_date DATE,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_hay_cutting_field CHECK (TRIM(field_name) <> ''),
    CONSTRAINT ck_hay_cutting_crop CHECK (TRIM(forage_crop) <> ''),
    CONSTRAINT ck_hay_cutting_number CHECK (cutting_number BETWEEN 1 AND 99),
    CONSTRAINT ck_hay_cutting_acres CHECK (acres IS NULL OR (acres > 0 AND acres <= 1000000.00)),
    CONSTRAINT ck_hay_cutting_dates CHECK (
        planned_bale_date IS NULL OR planned_bale_date >= planned_cut_date),
    CONSTRAINT ck_hay_cutting_stage CHECK (
        stage IN ('PLANNED', 'CUT', 'CURING', 'BALED', 'STORED'))
);

CREATE INDEX idx_hay_cutting_field ON hay_cuttings(field_name);
CREATE INDEX idx_hay_cutting_cut_date ON hay_cuttings(planned_cut_date);
