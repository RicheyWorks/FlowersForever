-- The scouting log (findings, lab samples, photo links) moves from
-- <records folder>/scouting/scouting-log.json into the farm database.
-- The app copies the JSON file in once (json_imported_at records when) and leaves
-- the file untouched as a backup. Photo bytes stay in the attachments folder;
-- these rows link to them by SHA-256 and size.
-- Sample-to-finding links are kept by code, as in the JSON log, and are checked
-- by the app (a finding with samples cannot be deleted).

CREATE TABLE scouting_findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL,
    found_on DATE,
    planting_id BIGINT,
    bed VARCHAR(1000) NOT NULL DEFAULT '',
    crop VARCHAR(1000) NOT NULL DEFAULT '',
    variety VARCHAR(1000) NOT NULL DEFAULT '',
    category VARCHAR(20) NOT NULL,
    organism VARCHAR(1000) NOT NULL DEFAULT '',
    symptoms VARCHAR(10000) NOT NULL DEFAULT '',
    severity VARCHAR(20) NOT NULL,
    incidence_percent DOUBLE PRECISION,
    photo_path VARCHAR(4000) NOT NULL DEFAULT '',
    action_taken VARCHAR(10000) NOT NULL DEFAULT '',
    CONSTRAINT uk_scouting_finding_code UNIQUE (code),
    CONSTRAINT ck_scouting_finding_category
        CHECK (category IN ('INSECT_MITE', 'FUNGAL', 'BACTERIAL', 'VIRAL', 'ABIOTIC', 'UNKNOWN')),
    CONSTRAINT ck_scouting_finding_severity
        CHECK (severity IN ('LOW', 'MODERATE', 'HIGH', 'SEVERE'))
);

CREATE INDEX idx_scouting_finding_found_on ON scouting_findings(found_on, code);

CREATE TABLE scouting_finding_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id BIGINT NOT NULL,
    position INTEGER NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    media_type VARCHAR(255) NOT NULL DEFAULT '',
    byte_size BIGINT NOT NULL,
    filename VARCHAR(1000) NOT NULL DEFAULT '',
    caption VARCHAR(1000) NOT NULL DEFAULT '',
    added_on DATE,
    CONSTRAINT fk_scouting_photo_finding
        FOREIGN KEY (finding_id) REFERENCES scouting_findings(id) ON DELETE CASCADE,
    CONSTRAINT uk_scouting_photo_position UNIQUE (finding_id, position)
);

CREATE INDEX idx_scouting_photo_sha256 ON scouting_finding_photos(sha256);

CREATE TABLE scouting_lab_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL,
    finding_code VARCHAR(200) NOT NULL DEFAULT '',
    soil_block VARCHAR(1000) NOT NULL DEFAULT '',
    sample_type VARCHAR(20) NOT NULL,
    lab_id VARCHAR(200) NOT NULL DEFAULT '',
    lab_name VARCHAR(1000) NOT NULL DEFAULT '',
    collected_on DATE,
    shipped_on DATE,
    tracking VARCHAR(1000) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL,
    cost DECIMAL(19, 4),
    result_summary VARCHAR(10000) NOT NULL DEFAULT '',
    report_path VARCHAR(4000) NOT NULL DEFAULT '',
    results_on DATE,
    CONSTRAINT uk_scouting_sample_code UNIQUE (code),
    CONSTRAINT ck_scouting_sample_type CHECK (sample_type IN ('PLANT_DISEASE', 'INSECT', 'SOIL', 'WATER')),
    CONSTRAINT ck_scouting_sample_status CHECK (status IN ('COLLECTED', 'SHIPPED', 'RECEIVED', 'RESULTS_IN'))
);

CREATE INDEX idx_scouting_sample_finding ON scouting_lab_samples(finding_code);

CREATE TABLE scouting_settings (
    id INTEGER PRIMARY KEY,
    log_version INTEGER NOT NULL DEFAULT 1,
    overdue_days INTEGER NOT NULL DEFAULT 14,
    json_imported_at TIMESTAMP(6) WITH TIME ZONE,
    json_import_note VARCHAR(2000),
    CONSTRAINT ck_scouting_settings_single_row CHECK (id = 1),
    CONSTRAINT ck_scouting_settings_overdue_days CHECK (overdue_days BETWEEN 1 AND 120)
);

