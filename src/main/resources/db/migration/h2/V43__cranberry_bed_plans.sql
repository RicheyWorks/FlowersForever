-- Wet/dry choice and harvest window are plans, not actual harvest or sales records.
CREATE TABLE cranberry_bed_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bed_name VARCHAR(120) NOT NULL,
    variety VARCHAR(120) NOT NULL,
    acres DECIMAL(12, 2),
    harvest_method VARCHAR(24) NOT NULL,
    planned_harvest_start DATE,
    planned_harvest_end DATE,
    intended_channel VARCHAR(120) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_cranberry_bed_name CHECK (TRIM(bed_name) <> ''),
    CONSTRAINT ck_cranberry_acres CHECK (acres IS NULL OR acres > 0),
    CONSTRAINT ck_cranberry_harvest_method CHECK (
        harvest_method IN ('UNDECIDED', 'WET', 'DRY', 'MIXED')),
    CONSTRAINT ck_cranberry_harvest_end CHECK (
        planned_harvest_end IS NULL OR
        (planned_harvest_start IS NOT NULL
         AND planned_harvest_end >= planned_harvest_start)),
    CONSTRAINT ck_cranberry_stage CHECK (
        stage IN ('PLANNED', 'GROWING', 'HARVEST_PREP', 'HARVEST_WINDOW'))
);

CREATE INDEX idx_cranberry_harvest_start
    ON cranberry_bed_plans(planned_harvest_start);
