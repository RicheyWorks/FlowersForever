-- Field plans do not post harvested yields, grades, stock, storage, or orders.
CREATE TABLE grain_field_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_name VARCHAR(120) NOT NULL,
    grain_crop VARCHAR(120) NOT NULL,
    variety VARCHAR(120) NOT NULL,
    acres DECIMAL(9, 2),
    previous_crop VARCHAR(120) NOT NULL,
    planned_seeding_date DATE,
    planned_harvest_start DATE NOT NULL,
    planned_harvest_end DATE,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_grain_field_name CHECK (TRIM(field_name) <> ''),
    CONSTRAINT ck_grain_field_crop CHECK (TRIM(grain_crop) <> ''),
    CONSTRAINT ck_grain_field_acres CHECK (acres IS NULL OR (acres > 0 AND acres <= 1000000.00)),
    CONSTRAINT ck_grain_field_seeding_date CHECK (
        planned_seeding_date IS NULL OR planned_seeding_date <= planned_harvest_start),
    CONSTRAINT ck_grain_field_dates CHECK (
        planned_harvest_end IS NULL OR planned_harvest_end >= planned_harvest_start),
    CONSTRAINT ck_grain_field_stage CHECK (
        stage IN ('PLANNED', 'SEEDED', 'ESTABLISHED', 'GROWING', 'HARVEST_WINDOW'))
);

CREATE INDEX idx_grain_field_crop ON grain_field_plans(grain_crop);
CREATE INDEX idx_grain_field_harvest_start ON grain_field_plans(planned_harvest_start);
