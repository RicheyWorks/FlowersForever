-- Yard plans do not post harvested yields, drying, pellets, stock, or orders.
CREATE TABLE hop_yard_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    yard_name VARCHAR(120) NOT NULL,
    hop_variety VARCHAR(120) NOT NULL,
    acres DECIMAL(9, 2),
    planned_stringing_date DATE,
    planned_harvest_start DATE NOT NULL,
    planned_harvest_end DATE,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_hop_yard_name CHECK (TRIM(yard_name) <> ''),
    CONSTRAINT ck_hop_yard_variety CHECK (TRIM(hop_variety) <> ''),
    CONSTRAINT ck_hop_yard_acres CHECK (acres IS NULL OR (acres > 0 AND acres <= 1000000.00)),
    CONSTRAINT ck_hop_yard_stringing_date CHECK (
        planned_stringing_date IS NULL OR planned_stringing_date <= planned_harvest_start),
    CONSTRAINT ck_hop_yard_dates CHECK (
        planned_harvest_end IS NULL OR planned_harvest_end >= planned_harvest_start),
    CONSTRAINT ck_hop_yard_stage CHECK (
        stage IN ('PLANNED', 'STRINGING', 'TRAINING', 'CONE_DEVELOPMENT', 'HARVEST_WINDOW'))
);

CREATE INDEX idx_hop_yard_variety ON hop_yard_plans(hop_variety);
CREATE INDEX idx_hop_yard_harvest_start ON hop_yard_plans(planned_harvest_start);
