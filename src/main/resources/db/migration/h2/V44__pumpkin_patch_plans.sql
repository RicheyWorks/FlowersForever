-- These are plans, not completed harvest, admissions, bookings, or payments.
CREATE TABLE pumpkin_patch_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patch_name VARCHAR(120) NOT NULL,
    variety VARCHAR(120) NOT NULL,
    acres DECIMAL(12, 2),
    planned_planting_date DATE,
    planned_picking_start DATE,
    planned_picking_end DATE,
    sales_mode VARCHAR(24) NOT NULL,
    visitor_area_notes VARCHAR(2000) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_pumpkin_patch_name CHECK (TRIM(patch_name) <> ''),
    CONSTRAINT ck_pumpkin_acres CHECK (acres IS NULL OR acres > 0),
    CONSTRAINT ck_pumpkin_planting_picking CHECK (
        planned_picking_start IS NULL OR planned_planting_date IS NULL
        OR planned_picking_start >= planned_planting_date),
    CONSTRAINT ck_pumpkin_picking_end CHECK (
        planned_picking_end IS NULL OR
        (planned_picking_start IS NOT NULL
         AND planned_picking_end >= planned_picking_start)),
    CONSTRAINT ck_pumpkin_sales_mode CHECK (
        sales_mode IN ('UNDECIDED', 'PICK_YOUR_OWN', 'FARM_STAND',
                       'WHOLESALE', 'MIXED')),
    CONSTRAINT ck_pumpkin_stage CHECK (
        stage IN ('PLANNED', 'PLANTING_WINDOW', 'GROWING', 'PICKING_WINDOW'))
);

CREATE INDEX idx_pumpkin_picking_start
    ON pumpkin_patch_plans(planned_picking_start);
