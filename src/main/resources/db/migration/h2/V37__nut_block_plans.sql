-- Block plans do not record actual harvest, processing, quality, stock, or sales.
CREATE TABLE nut_block_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_name VARCHAR(120) NOT NULL,
    nut_crop VARCHAR(120) NOT NULL,
    variety VARCHAR(120) NOT NULL,
    pollinizer_variety VARCHAR(120) NOT NULL,
    acres DECIMAL(9, 2),
    tree_count INTEGER,
    planned_bloom_start DATE,
    planned_floor_prep_date DATE,
    planned_harvest_start DATE NOT NULL,
    planned_harvest_end DATE,
    intended_destination VARCHAR(120) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_nut_block_name CHECK (TRIM(block_name) <> ''),
    CONSTRAINT ck_nut_block_crop CHECK (TRIM(nut_crop) <> ''),
    CONSTRAINT ck_nut_block_acres CHECK (acres IS NULL OR (acres > 0 AND acres <= 1000000.00)),
    CONSTRAINT ck_nut_block_tree_count CHECK (tree_count IS NULL OR tree_count > 0),
    CONSTRAINT ck_nut_block_bloom CHECK (
        planned_bloom_start IS NULL OR planned_bloom_start <= planned_harvest_start),
    CONSTRAINT ck_nut_block_floor_prep CHECK (
        planned_floor_prep_date IS NULL OR planned_floor_prep_date <= planned_harvest_start),
    CONSTRAINT ck_nut_block_harvest_dates CHECK (
        planned_harvest_end IS NULL OR planned_harvest_end >= planned_harvest_start),
    CONSTRAINT ck_nut_block_stage CHECK (
        stage IN ('PLANNED', 'POLLINATION', 'NUT_SET', 'FLOOR_PREP', 'HARVEST_WINDOW'))
);

CREATE INDEX idx_nut_block_crop ON nut_block_plans(nut_crop);
CREATE INDEX idx_nut_block_harvest_start ON nut_block_plans(planned_harvest_start);
