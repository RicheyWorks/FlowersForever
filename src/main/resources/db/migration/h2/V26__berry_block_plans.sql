    DROP CONSTRAINT ck_farm_operation_workspace;

ALTER TABLE farm_operation_settings
    ADD CONSTRAINT ck_farm_operation_workspace CHECK (
        workspace_code IN ('ROSE_AND_EVENTS', 'WILDFLOWER_FARM',
                           'FLOWER_SHOP', 'CANNABIS_FARM', 'POTATO_FARM',
                           'APPLE_ORCHARD', 'BERRY_FARM', 'CUSTOM_FARM'));

-- Planning only; picking records do not create harvest lots, stock, or orders.
CREATE TABLE berry_block_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_name VARCHAR(120) NOT NULL,
    crop VARCHAR(120) NOT NULL,
    cultivar VARCHAR(120) NOT NULL,
    acres DECIMAL(9, 2),
    planting_date DATE,
    first_pick_date DATE,
    last_pick_date DATE,
    sales_channel VARCHAR(16) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_berry_block_name CHECK (TRIM(block_name) <> ''),
    CONSTRAINT ck_berry_block_crop CHECK (TRIM(crop) <> ''),
    CONSTRAINT ck_berry_block_acres CHECK (acres > 0 AND acres <= 1000000),
    CONSTRAINT ck_berry_block_first_pick CHECK (
        planting_date IS NULL OR first_pick_date IS NULL
        OR first_pick_date >= planting_date),
    CONSTRAINT ck_berry_block_last_pick CHECK (
        first_pick_date IS NULL OR last_pick_date IS NULL
        OR last_pick_date >= first_pick_date),
    CONSTRAINT ck_berry_block_last_after_planting CHECK (
        planting_date IS NULL OR last_pick_date IS NULL
        OR last_pick_date >= planting_date),
    CONSTRAINT ck_berry_block_channel CHECK (sales_channel IN (
        'UNDECIDED', 'FRESH', 'PROCESSING', 'U_PICK', 'MIXED')),
    CONSTRAINT ck_berry_block_stage CHECK (stage IN (
        'PLANNED', 'ESTABLISHING', 'GROWING', 'PICKING',
        'PICKED', 'COMPLETE', 'CANCELLED'))
);

CREATE INDEX idx_berry_block_crop ON berry_block_plans(crop);
CREATE INDEX idx_berry_block_first_pick ON berry_block_plans(first_pick_date);
