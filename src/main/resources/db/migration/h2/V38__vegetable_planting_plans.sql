-- Plans do not record actual harvested yield, wash/pack, stock, or orders.
CREATE TABLE vegetable_planting_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_or_bed VARCHAR(120) NOT NULL,
    vegetable_crop VARCHAR(120) NOT NULL,
    variety VARCHAR(120) NOT NULL,
    previous_crop VARCHAR(120) NOT NULL,
    acres DECIMAL(9, 2),
    succession_number INTEGER NOT NULL,
    planned_sowing_date DATE,
    planned_transplant_date DATE,
    planned_harvest_start DATE NOT NULL,
    planned_harvest_end DATE,
    intended_channel VARCHAR(120) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_vegetable_planting_field CHECK (TRIM(field_or_bed) <> ''),
    CONSTRAINT ck_vegetable_planting_crop CHECK (TRIM(vegetable_crop) <> ''),
    CONSTRAINT ck_vegetable_planting_acres CHECK (
        acres IS NULL OR (acres > 0 AND acres <= 1000000.00)),
    CONSTRAINT ck_vegetable_planting_succession CHECK (succession_number > 0),
    CONSTRAINT ck_vegetable_planting_sowing CHECK (
        planned_sowing_date IS NULL OR planned_sowing_date <= planned_harvest_start),
    CONSTRAINT ck_vegetable_planting_transplant CHECK (
        planned_transplant_date IS NULL OR planned_transplant_date <= planned_harvest_start),
    CONSTRAINT ck_vegetable_planting_sowing_transplant CHECK (
        planned_sowing_date IS NULL OR planned_transplant_date IS NULL
        OR planned_sowing_date <= planned_transplant_date),
    CONSTRAINT ck_vegetable_planting_harvest_dates CHECK (
        planned_harvest_end IS NULL OR planned_harvest_end >= planned_harvest_start),
    CONSTRAINT ck_vegetable_planting_stage CHECK (
        stage IN ('PLANNED', 'SOWN', 'TRANSPLANTED', 'GROWING', 'HARVEST_WINDOW'))
);

CREATE INDEX idx_vegetable_planting_crop
    ON vegetable_planting_plans(vegetable_crop);
CREATE INDEX idx_vegetable_planting_harvest_start
    ON vegetable_planting_plans(planned_harvest_start);
