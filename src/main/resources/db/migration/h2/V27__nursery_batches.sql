    DROP CONSTRAINT ck_farm_operation_workspace;

ALTER TABLE farm_operation_settings
    ADD CONSTRAINT ck_farm_operation_workspace CHECK (
        workspace_code IN ('ROSE_AND_EVENTS', 'WILDFLOWER_FARM',
                           'FLOWER_SHOP', 'CANNABIS_FARM', 'POTATO_FARM',
                           'APPLE_ORCHARD', 'BERRY_FARM', 'NURSERY_FARM',
                           'CUSTOM_FARM'));

-- Planning only; batches do not create stock, orders, or regulatory records.
CREATE TABLE nursery_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_name VARCHAR(120) NOT NULL,
    plant_name VARCHAR(120) NOT NULL,
    cultivar VARCHAR(120) NOT NULL,
    plant_form VARCHAR(24) NOT NULL,
    growing_area VARCHAR(128) NOT NULL,
    started_date DATE,
    planned_ready_date DATE,
    starting_count INTEGER,
    sales_channel VARCHAR(16) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_nursery_batch_name CHECK (TRIM(batch_name) <> ''),
    CONSTRAINT ck_nursery_plant_name CHECK (TRIM(plant_name) <> ''),
    CONSTRAINT ck_nursery_dates CHECK (
        started_date IS NULL OR planned_ready_date IS NULL
        OR planned_ready_date >= started_date),
    CONSTRAINT ck_nursery_starting_count CHECK (
        starting_count IS NULL OR starting_count BETWEEN 1 AND 1000000),
    CONSTRAINT ck_nursery_plant_form CHECK (plant_form IN (
        'UNSPECIFIED', 'STARTS_OR_PLUGS', 'POTTED', 'BARE_ROOT',
        'BULBS_OR_CUTTINGS', 'OTHER')),
    CONSTRAINT ck_nursery_sales_channel CHECK (sales_channel IN (
        'UNDECIDED', 'RETAIL', 'WHOLESALE', 'LANDSCAPE', 'MIXED')),
    CONSTRAINT ck_nursery_stage CHECK (stage IN (
        'PLANNED', 'PROPAGATING', 'GROWING', 'HARDENING_OFF',
        'READY_FOR_SALE', 'COMPLETE', 'CANCELLED'))
);

CREATE INDEX idx_nursery_plant_name ON nursery_batches(plant_name);
CREATE INDEX idx_nursery_planned_ready ON nursery_batches(planned_ready_date);
