-- Durable operation identities make phone/tablet field retries apply exactly once.

CREATE TABLE worker_action_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_record_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    action VARCHAR(32) NOT NULL,
    operation_key_hash VARCHAR(64) NOT NULL,
    request_fingerprint VARCHAR(64) NOT NULL,
    response_sha256 VARCHAR(64) NOT NULL,
    response_json CLOB NOT NULL,
    CONSTRAINT ck_worker_action_target CHECK (target_record_id > 0),
    CONSTRAINT ck_worker_action_key_hash CHECK (LENGTH(operation_key_hash) = 64),
    CONSTRAINT ck_worker_action_request_hash CHECK (LENGTH(request_fingerprint) = 64),
    CONSTRAINT ck_worker_action_response_hash CHECK (LENGTH(response_sha256) = 64),
    CONSTRAINT ck_worker_action_type CHECK (
        action IN ('LOG_HARVEST', 'COMPLETE_TASK')),
    CONSTRAINT uk_worker_action_key UNIQUE (operation_key_hash)
);

CREATE INDEX idx_worker_action_created ON worker_action_receipts(created_at);
