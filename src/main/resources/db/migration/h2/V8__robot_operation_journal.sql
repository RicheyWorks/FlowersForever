-- Append-only recovery journal for long-running robot operations.

CREATE TABLE robot_operation_events (
    progress_percent FLOAT(53) NOT NULL,
    simulated BOOLEAN NOT NULL,
    accepted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    observed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    recorded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plugin_id VARCHAR(30) NOT NULL,
    action VARCHAR(30) NOT NULL,
    status VARCHAR(24) NOT NULL,
    robot_id VARCHAR(120) NOT NULL,
    operation_id VARCHAR(160) NOT NULL,
    status_message VARCHAR(500) NOT NULL,
    CONSTRAINT chk_robot_operation_progress CHECK (
        progress_percent BETWEEN 0 AND 100),
    CONSTRAINT chk_robot_operation_status CHECK (
        status IN ('IDLE', 'STAGED', 'RUNNING', 'SUCCEEDED', 'FAILED',
                   'CANCELLED', 'STOPPED', 'UNKNOWN'))
);

CREATE INDEX idx_robot_operation_lookup
    ON robot_operation_events(plugin_id, operation_id, id);
CREATE INDEX idx_robot_operation_recorded
    ON robot_operation_events(recorded_at);
