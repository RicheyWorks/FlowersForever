-- Plans do not record actual cutting, stock, sales, or inspection events.
CREATE TABLE christmas_tree_block_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_name VARCHAR(120) NOT NULL,
    tree_species VARCHAR(120) NOT NULL,
    planting_year INTEGER,
    acres DECIMAL(12, 2),
    planted_tree_count INTEGER,
    target_height VARCHAR(80) NOT NULL,
    next_shearing_date DATE,
    target_harvest_year INTEGER NOT NULL,
    planned_cut_start DATE,
    planned_cut_end DATE,
    intended_channel VARCHAR(120) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_christmas_tree_block_name CHECK (TRIM(block_name) <> ''),
    CONSTRAINT ck_christmas_tree_species CHECK (TRIM(tree_species) <> ''),
    CONSTRAINT ck_christmas_tree_harvest_year CHECK (
        target_harvest_year BETWEEN 1900 AND 2200),
    CONSTRAINT ck_christmas_tree_planting_year CHECK (
        planting_year IS NULL OR (planting_year BETWEEN 1900 AND 2200
                                  AND planting_year <= target_harvest_year)),
    CONSTRAINT ck_christmas_tree_acres CHECK (acres IS NULL OR acres > 0),
    CONSTRAINT ck_christmas_tree_count CHECK (
        planted_tree_count IS NULL OR planted_tree_count > 0),
    CONSTRAINT ck_christmas_tree_cut_start CHECK (
        planned_cut_start IS NULL OR
        EXTRACT(YEAR FROM planned_cut_start) = target_harvest_year),
    CONSTRAINT ck_christmas_tree_cut_end CHECK (
        planned_cut_end IS NULL OR
        (planned_cut_start IS NOT NULL AND planned_cut_end >= planned_cut_start
         AND EXTRACT(YEAR FROM planned_cut_end) = target_harvest_year)),
    CONSTRAINT ck_christmas_tree_shearing CHECK (
        next_shearing_date IS NULL OR
        (EXTRACT(YEAR FROM next_shearing_date) <= target_harvest_year
         AND (planned_cut_start IS NULL
              OR next_shearing_date <= planned_cut_start))),
    CONSTRAINT ck_christmas_tree_stage CHECK (
        stage IN ('PLANNED', 'GROWING', 'SHEARING', 'HARVEST_WINDOW'))
);

CREATE INDEX idx_christmas_tree_species
    ON christmas_tree_block_plans(tree_species);
CREATE INDEX idx_christmas_tree_harvest_year
    ON christmas_tree_block_plans(target_harvest_year);
