-- A milk collection is an operational note, not inventory or a sales transaction.
CREATE TABLE milk_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_date DATE NOT NULL,
    group_name VARCHAR(120) NOT NULL,
    session_name VARCHAR(120) NOT NULL,
    tank_location VARCHAR(128) NOT NULL,
    amount DECIMAL(9, 2) NOT NULL,
    unit_code VARCHAR(16) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_milk_collection_group CHECK (TRIM(group_name) <> ''),
    CONSTRAINT ck_milk_collection_session CHECK (TRIM(session_name) <> ''),
    CONSTRAINT ck_milk_collection_amount CHECK (amount > 0 AND amount <= 1000000.00),
    CONSTRAINT ck_milk_collection_unit CHECK (unit_code IN ('POUNDS', 'GALLONS', 'LITERS'))
);

CREATE INDEX idx_milk_collection_date ON milk_collections(collection_date);
CREATE INDEX idx_milk_collection_group ON milk_collections(group_name);
