-- Plans do not record actual stocking, harvest, stock, sales, or compliance events.
CREATE TABLE aquatic_cohort_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cohort_name VARCHAR(120) NOT NULL,
    species VARCHAR(120) NOT NULL,
    growing_site VARCHAR(120) NOT NULL,
    culture_method VARCHAR(120) NOT NULL,
    planned_stocking_date DATE,
    planned_harvest_start DATE NOT NULL,
    planned_harvest_end DATE,
    intended_destination VARCHAR(120) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_aquatic_cohort_name CHECK (TRIM(cohort_name) <> ''),
    CONSTRAINT ck_aquatic_cohort_species CHECK (TRIM(species) <> ''),
    CONSTRAINT ck_aquatic_cohort_site CHECK (TRIM(growing_site) <> ''),
    CONSTRAINT ck_aquatic_cohort_stocking_date CHECK (
        planned_stocking_date IS NULL OR planned_stocking_date <= planned_harvest_start),
    CONSTRAINT ck_aquatic_cohort_harvest_dates CHECK (
        planned_harvest_end IS NULL OR planned_harvest_end >= planned_harvest_start),
    CONSTRAINT ck_aquatic_cohort_stage CHECK (
        stage IN ('PLANNED', 'STOCKING_WINDOW', 'GROWING_OUT', 'HARVEST_WINDOW'))
);

CREATE INDEX idx_aquatic_cohort_species
    ON aquatic_cohort_plans(species);
CREATE INDEX idx_aquatic_cohort_harvest_start
    ON aquatic_cohort_plans(planned_harvest_start);
