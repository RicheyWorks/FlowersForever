-- Farm-owned observations, actions, outcomes, follow-ups, and reusable tags.
-- Operational record links clear on delete so the lesson itself is preserved.

CREATE TABLE knowledge_entries (
    observed_on DATE NOT NULL,
    follow_up_date DATE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    customer_id BIGINT,
    harvest_id BIGINT,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_item_id BIGINT,
    order_id BIGINT,
    kind VARCHAR(24) NOT NULL,
    confidence VARCHAR(24) NOT NULL,
    bed_or_field VARCHAR(128),
    production_stage VARCHAR(128),
    summary VARCHAR(180) NOT NULL,
    crop_name VARCHAR(255),
    performed_by VARCHAR(255),
    variety VARCHAR(255),
    action_taken VARCHAR(2000),
    observation VARCHAR(2000) NOT NULL,
    result VARCHAR(2000),
    CONSTRAINT fk_knowledge_customer
        FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE SET NULL,
    CONSTRAINT fk_knowledge_harvest
        FOREIGN KEY (harvest_id) REFERENCES harvest_log(id) ON DELETE SET NULL,
    CONSTRAINT fk_knowledge_inventory
        FOREIGN KEY (inventory_item_id) REFERENCES inventory_items(id) ON DELETE SET NULL,
    CONSTRAINT fk_knowledge_order
        FOREIGN KEY (order_id) REFERENCES customer_orders(id) ON DELETE SET NULL
);

CREATE TABLE knowledge_entry_tags (
    knowledge_entry_id BIGINT NOT NULL,
    tag VARCHAR(64) NOT NULL,
    PRIMARY KEY (knowledge_entry_id, tag),
    CONSTRAINT fk_knowledge_tags_entry
        FOREIGN KEY (knowledge_entry_id) REFERENCES knowledge_entries(id) ON DELETE CASCADE
);

CREATE INDEX idx_knowledge_observed ON knowledge_entries(observed_on);
CREATE INDEX idx_knowledge_follow_up ON knowledge_entries(follow_up_date);
CREATE INDEX idx_knowledge_crop ON knowledge_entries(crop_name);
CREATE INDEX idx_knowledge_tag ON knowledge_entry_tags(tag);
