-- Exact plain-text exports copied from the pinned offline CSRBT instruments.
-- Export bytes live in H2 alongside farm records and are included in database backups.

CREATE TABLE field_science_exports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    instrument_id VARCHAR(64) NOT NULL,
    instrument_title VARCHAR(180) NOT NULL,
    source_url VARCHAR(512) NOT NULL,
    source_commit VARCHAR(40) NOT NULL,
    title VARCHAR(180) NOT NULL,
    filename VARCHAR(255),
    note VARCHAR(500),
    byte_length INTEGER NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    content CLOB NOT NULL,
    CONSTRAINT ck_field_science_export_length
        CHECK (byte_length BETWEEN 1 AND 524288),
    CONSTRAINT ck_field_science_export_sha256 CHECK (LENGTH(sha256) = 64)
);

CREATE INDEX idx_field_science_export_created
    ON field_science_exports(created_at, id);
CREATE INDEX idx_field_science_export_instrument
    ON field_science_exports(instrument_id, created_at);
