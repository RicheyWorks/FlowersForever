-- Farm-owned crop templates, frost anchors, generated work, recipes, and safe handoffs.

CREATE TABLE farm_season_settings (
    season_year INTEGER NOT NULL,
    last_spring_frost DATE NOT NULL,
    first_fall_frost DATE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(255) NOT NULL,
    CONSTRAINT uk_farm_season_year UNIQUE (season_year),
    CONSTRAINT chk_farm_season_year CHECK (season_year BETWEEN 2000 AND 2200),
    CONSTRAINT chk_farm_frost_window CHECK (first_fall_frost > last_spring_frost)
);

CREATE TABLE growing_templates (
    spacing_inches FLOAT(53) NOT NULL,
    stems_per_plant FLOAT(53) NOT NULL,
    germination_percent FLOAT(53) NOT NULL,
    rows_per_bed INTEGER NOT NULL,
    sow_days_from_frost INTEGER NOT NULL,
    transplant_days_from_frost INTEGER,
    days_to_harvest INTEGER NOT NULL,
    harvest_window_days INTEGER NOT NULL,
    succession_days INTEGER NOT NULL,
    soil_prep_lead_days INTEGER NOT NULL,
    support_days_after_planting INTEGER NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    crop_name VARCHAR(120) NOT NULL,
    variety VARCHAR(120) NOT NULL,
    notes VARCHAR(1000),
    CONSTRAINT chk_template_spacing CHECK (spacing_inches BETWEEN 1 AND 72),
    CONSTRAINT chk_template_rows CHECK (rows_per_bed BETWEEN 1 AND 12),
    CONSTRAINT chk_template_germination CHECK (germination_percent BETWEEN 1 AND 100),
    CONSTRAINT chk_template_offsets CHECK (
        sow_days_from_frost BETWEEN -365 AND 365
        AND (transplant_days_from_frost IS NULL OR
            transplant_days_from_frost BETWEEN sow_days_from_frost AND 365)),
    CONSTRAINT chk_template_yield CHECK (stems_per_plant > 0),
    CONSTRAINT chk_template_maturity CHECK (
        days_to_harvest BETWEEN 1 AND 730
        AND harvest_window_days BETWEEN 1 AND 365
        AND succession_days BETWEEN 0 AND 365)
);

CREATE INDEX idx_growing_template_crop ON growing_templates(crop_name);

CREATE TABLE production_tasks (
    due_date DATE NOT NULL,
    sequence_number INTEGER NOT NULL,
    generated BOOLEAN NOT NULL,
    season_plan_id BIGINT,
    growing_template_id BIGINT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    crop_name VARCHAR(120) NOT NULL,
    bed_or_field VARCHAR(128) NOT NULL,
    notes VARCHAR(1000),
    CONSTRAINT fk_production_task_plan FOREIGN KEY (season_plan_id)
        REFERENCES season_plan_entries(id) ON DELETE CASCADE
);

CREATE INDEX idx_production_task_due ON production_tasks(due_date, status);
CREATE INDEX idx_production_task_plan ON production_tasks(season_plan_id);

CREATE TABLE floral_recipes (
    sale_price FLOAT(53) NOT NULL,
    labor_minutes INTEGER NOT NULL,
    labor_rate_hour FLOAT(53) NOT NULL,
    overhead_percent FLOAT(53) NOT NULL,
    waste_percent FLOAT(53) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    design_type VARCHAR(64) NOT NULL,
    notes VARCHAR(1200),
    CONSTRAINT chk_recipe_economics CHECK (
        sale_price >= 0 AND labor_minutes >= 0 AND labor_rate_hour >= 0
        AND overhead_percent BETWEEN 0 AND 500 AND waste_percent BETWEEN 0 AND 500)
);

CREATE TABLE floral_recipe_ingredients (
    stems_per_design FLOAT(53) NOT NULL,
    pack_size INTEGER NOT NULL,
    pack_cost FLOAT(53) NOT NULL,
    recipe_id BIGINT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR(255) NOT NULL,
    notes VARCHAR(500),
    CONSTRAINT fk_recipe_ingredient_recipe FOREIGN KEY (recipe_id)
        REFERENCES floral_recipes(id) ON DELETE CASCADE,
    CONSTRAINT chk_recipe_ingredient CHECK (
        stems_per_design > 0 AND pack_size > 0 AND pack_cost >= 0)
);

CREATE INDEX idx_recipe_ingredient_recipe ON floral_recipe_ingredients(recipe_id);

CREATE TABLE integration_handoffs (
    amount FLOAT(53) NOT NULL,
    related_order_id BIGINT,
    related_recipe_id BIGINT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handoff_type VARCHAR(24) NOT NULL,
    provider VARCHAR(80) NOT NULL,
    status VARCHAR(24) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    external_reference VARCHAR(255) NOT NULL,
    payload_summary VARCHAR(2000) NOT NULL,
    CONSTRAINT chk_handoff_amount CHECK (amount >= 0)
);

CREATE INDEX idx_handoff_type_status ON integration_handoffs(handoff_type, status);
CREATE INDEX idx_handoff_order ON integration_handoffs(related_order_id);
