-- Collections are dated notes. They are not inventory or sales transactions.
CREATE TABLE egg_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_date DATE NOT NULL,
    flock_name VARCHAR(120) NOT NULL,
    location VARCHAR(128) NOT NULL,
    collected_count INTEGER NOT NULL,
    unusable_count INTEGER NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_egg_collection_flock CHECK (TRIM(flock_name) <> ''),
    CONSTRAINT ck_egg_collection_collected CHECK (collected_count BETWEEN 0 AND 1000000),
    CONSTRAINT ck_egg_collection_unusable CHECK (unusable_count BETWEEN 0 AND collected_count)
);

CREATE INDEX idx_egg_collection_date ON egg_collections(collection_date);
CREATE INDEX idx_egg_collection_flock ON egg_collections(flock_name);
