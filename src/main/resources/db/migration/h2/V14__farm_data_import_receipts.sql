-- Durable source identities make AI and legacy-data imports resumable across restarts.

CREATE TABLE farm_data_import_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_record_id BIGINT NOT NULL,
    imported_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    source_system VARCHAR(120) NOT NULL,
    record_type VARCHAR(32) NOT NULL,
    action VARCHAR(30) NOT NULL,
    content_fingerprint VARCHAR(64) NOT NULL,
    source_key VARCHAR(240) NOT NULL,
    CONSTRAINT ck_farm_data_import_fingerprint
        CHECK (LENGTH(content_fingerprint) = 64),
    CONSTRAINT ck_farm_data_import_target
        CHECK (target_record_id > 0),
    CONSTRAINT uk_farm_data_source_record
        UNIQUE (source_system, record_type, source_key)
);

CREATE INDEX idx_farm_data_import_updated
    ON farm_data_import_receipts(updated_at);
