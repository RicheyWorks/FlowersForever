-- Extend the desktop workspace choice for dedicated potato and apple notebooks.
ALTER TABLE farm_operation_settings
    DROP CONSTRAINT ck_farm_operation_workspace;

ALTER TABLE farm_operation_settings
    ADD CONSTRAINT ck_farm_operation_workspace CHECK (
        workspace_code IN ('ROSE_AND_EVENTS', 'WILDFLOWER_FARM',
                           'FLOWER_SHOP', 'CANNABIS_FARM', 'POTATO_FARM',
                           'APPLE_ORCHARD', 'CUSTOM_FARM'));

-- Local planning only; no yield, packout, inventory, or sales linkage.
CREATE TABLE crop_area_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_code VARCHAR(32) NOT NULL,
    area_name VARCHAR(120) NOT NULL,
    variety VARCHAR(120) NOT NULL,
    acres DECIMAL(9, 2),
    planting_date DATE,
    target_harvest_date DATE,
    stage VARCHAR(24) NOT NULL,
    notes VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_crop_area_workspace CHECK (
        workspace_code IN ('POTATO_FARM', 'APPLE_ORCHARD')),
    CONSTRAINT ck_crop_area_acres CHECK (acres > 0 AND acres <= 1000000),
    CONSTRAINT ck_crop_area_dates CHECK (
        planting_date IS NULL OR target_harvest_date IS NULL
        OR target_harvest_date >= planting_date),
    CONSTRAINT ck_crop_area_stage CHECK (stage IN (
        'PLANNED', 'ESTABLISHING', 'GROWING', 'HARVEST_READY',
        'HARVESTED', 'COMPLETE', 'CANCELLED'))
);

CREATE INDEX idx_crop_area_workspace ON crop_area_plans(workspace_code);
CREATE INDEX idx_crop_area_target_harvest ON crop_area_plans(target_harvest_date);
